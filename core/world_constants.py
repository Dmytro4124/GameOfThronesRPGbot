# === ФУНКЦІЇ ВАЛІДАЦІЇ ===

def get_locations_for_region(region: str) -> list:
    """Повертає список канонічних локацій для заданого регіону."""
    return [loc for loc, reg in LOCATION_TO_REGION.items() if reg == region]


def get_region_for_location(location: str):
    """
    Повертає Регіон для вказаної Локації.
    Повертає None для TRAVEL_LOCATION (region зберігається без змін) та невідомих локацій.
    """
    stripped = str(location).strip()
    if stripped == TRAVEL_LOCATION:
        return None
    return LOCATION_TO_REGION.get(stripped)


def is_valid_region(region: str) -> bool:
    """Перевіряє, чи є рядок канонічним регіоном."""
    if not region:
        return False
    return str(region).strip() in VALID_REGIONS


def is_valid_location(location: str) -> bool:
    """
    Перевіряє, чи є рядок допустимою канонічною локацією або travel-sentinel.

    Повертає False для порожніх рядків та no-op значень ("none", "немає" тощо).
    Повертає True для: NPC_LOCATION_BYPASS ("GLOBAL"), TRAVEL_LOCATION ("В дорозі"),
    або будь-якого члена VALID_LOCATIONS.
    """
    if not location:
        return False
    stripped = str(location).strip()
    if stripped.lower() in ("none", "немає", "без змін", "", "null"):
        return False
    if stripped in (NPC_LOCATION_BYPASS, TRAVEL_LOCATION):
        return True
    return stripped in VALID_LOCATIONS


