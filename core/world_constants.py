def get_scenes_for_location(location: str) -> list[str]:
    """Повертає плоский список всіх валідних сцен для локації (fallback якщо локація невідома)."""
    loc_data = LOCATION_SCENES.get(location)
    if not loc_data:
        return _FALLBACK_SCENES
    return [s for scenes in loc_data.values() for s in scenes]


def is_valid_scene(location: str, scene: str) -> bool:
    """Перевіряє чи сцена є валідною для даної локації."""
    return scene in get_scenes_for_location(location)


def format_scenes_for_prompt(location: str) -> str:
    """Повертає відформатований блок для промпту: категорія + сцени + NPC-пул."""
    loc_data = LOCATION_SCENES.get(location)
    if not loc_data:
        fallback_names = ", ".join(f'"{s}"' for s in _FALLBACK_SCENES)
        return f"[ЗАГАЛЬНІ СЦЕНИ] {fallback_names}"
    lines = []
    for cat_key, scene_names in loc_data.items():
        cat = SCENE_DEFINITIONS.get(cat_key, {})
        label = cat.get("label", cat_key.upper())
        npc_hint = cat.get("npc_hint", "")
        forbidden = cat.get("forbidden_hint", "")
        names_str = ", ".join(f'"{s}"' for s in scene_names)
        line = f"[{label}] {names_str}"
        if npc_hint:
            line += f"\n  -> NPC-пул: {npc_hint}"
        if forbidden:
            line += f"\n  -> ЗАБОРОНЕНО: {forbidden}"
        lines.append(line)
    return "\n".join(lines)


